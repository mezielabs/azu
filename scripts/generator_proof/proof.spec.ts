/**
 * The generator proof (FR-04). scripts/prove_generator.mjs copies the
 * demo, removes its admin resources, policies and tests, runs
 * `node ace azu:resource <Model> --policy` for every model, then
 * runs this file there. With zero hand edits, every generated resource
 * must list, create, show and edit through the real HTTP stack.
 *
 * It knows nothing about the models: it reads each form from the page
 * props and fills it in from the field hints.
 */
import { randomUUID } from 'node:crypto'
import { test } from '@japa/runner'
import testUtils from '@adonisjs/core/services/test_utils'
import azu from '@mezielabs/azu/services/main'
import User from '#models/user'

/**
 * Resources the generated policy can't create from: their table has a
 * required column that isn't an admin field (users.password).
 */
const NO_CREATE = new Set(['users'])

type Field = {
  name: string
  input: string
  kind: string
  required: boolean
  maxLength: number | null
  options: Record<string, string> | null
  optionsUrl: string | null
}

function text(field: Field) {
  const value = `G${randomUUID().replace(/-/g, '').slice(0, 12)}`
  return field.maxLength ? value.slice(0, field.maxLength) : value
}

/**
 * A valid value for a field, from its hints.
 */
async function valueFor(field: Field, client: any, admin: User) {
  switch (field.kind) {
    case 'text':
      return text(field)
    case 'textarea':
      return 'Generated by the proof'
    case 'richText':
      return '<p>Generated by the <strong>proof</strong></p>'
    case 'number':
      return 1
    case 'decimal':
      return '1'
    case 'boolean':
      return true
    case 'select':
      return Object.keys(field.options ?? {})[0] ?? null
    case 'date':
      return '2026-10-14'
    case 'datetime':
      return new Date().toISOString()
    case 'belongsTo': {
      const response = await client.get(field.optionsUrl!).loginAs(admin)
      response.assertStatus(200)
      return response.body().options[0]?.id ?? null
    }
    // FR-09: attach the first option, so the pivot sync runs
    case 'manyToMany': {
      const response = await client.get(field.optionsUrl!).loginAs(admin)
      response.assertStatus(200)
      return response
        .body()
        .options.slice(0, 1)
        .map((option: { id: unknown }) => option.id)
    }
    default:
      return null
  }
}

async function payloadFor(fields: Field[], client: any, admin: User) {
  const payload: Record<string, unknown> = {}
  for (const field of fields) payload[field.input] = await valueFor(field, client, admin)
  return payload
}

test.group('Generated resources (FR-04)', (group) => {
  group.setup(() => testUtils.db().seed())

  const resources = azu.resources.all()

  test('every model has a generated resource', ({ assert }) => {
    assert.isAbove(resources.length, 0)
    console.log(`  ${resources.map((resource) => resource.name).join(', ')}`)
  })

  for (const resource of resources) {
    test(`${resource.name}: list, create, show and edit with zero hand edits`, async ({
      client,
      assert,
    }) => {
      const admin = await User.findByOrFail('email', 'admin@azu.test')
      const base = `/admin/resources/${resource.name}`

      const list = await client.get(base).loginAs(admin).withInertia()
      list.assertStatus(200)
      list.assertInertiaComponent('azu/resource/index')
      const canCreate = list.body().props.abilities.create
      assert.equal(canCreate, !NO_CREATE.has(resource.name))

      let id: string | number
      if (canCreate) {
        const form = await client.get(`${base}/create`).loginAs(admin).withInertia()
        form.assertStatus(200)
        const fields: Field[] = form.body().props.form.fields
        const created = await client
          .post(`${base}/create`)
          .loginAs(admin)
          .withInertia()
          .withCsrfToken()
          .json(await payloadFor(fields, client, admin))
          .redirects(0)
        assert.equal(
          created.status(),
          303,
          JSON.stringify(created.body()?.props?.errors ?? created.text())
        )
        id = String(created.header('location')).split('/').pop()!
      } else {
        id = list.body().props.list.rows[0].id
      }

      const show = await client.get(`${base}/${id}`).loginAs(admin).withInertia()
      show.assertStatus(200)
      show.assertInertiaComponent('azu/resource/show')

      const edit = await client.get(`${base}/${id}/edit`).loginAs(admin).withInertia()
      edit.assertStatus(200)
      const fields: Field[] = edit.body().props.form.fields
      const values = edit.body().props.form.values
      const payload: Record<string, unknown> = {}
      for (const field of fields) {
        const value = values[field.name]
        payload[field.input] =
          field.kind === 'belongsTo'
            ? (value?.id ?? null)
            : field.kind === 'manyToMany'
              ? (value ?? []).map((item: { id: unknown }) => item.id)
              : value
      }
      // Change the title so the save is visible
      const title = fields.find(
        (field) => field.name === resource.options.title && field.kind === 'text'
      )
      if (title) payload[title.input] = text(title)

      const updated = await client
        .put(`${base}/${id}/edit`)
        .loginAs(admin)
        .withInertia()
        .withCsrfToken()
        .json(payload)
        .redirects(0)
      assert.equal(
        updated.status(),
        303,
        JSON.stringify(updated.body()?.props?.errors ?? updated.text())
      )

      const after = await client.get(`${base}/${id}`).loginAs(admin).withInertia()
      if (title) {
        assert.equal(after.body().props.record.values[title.name], payload[title.input])
      }
      // The attached records survive the round trip
      for (const field of fields.filter((item) => item.kind === 'manyToMany')) {
        assert.deepEqual(
          after.body().props.record.values[field.name].map((item: { id: unknown }) => item.id),
          payload[field.input],
          `${resource.name}.${field.name}`
        )
      }
    })
  }
})
