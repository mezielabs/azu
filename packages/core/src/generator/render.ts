import string from '@adonisjs/core/helpers/string'
import { humanize } from '../resources/labels.ts'
import type { FieldPlan, ModelPlan } from './model_info.ts'

export type Names = {
  model: string
  /** `#models/order_item` */
  modelImport: string
  /** `OrderItemPolicy`, `#policies/order_item_policy` */
  policy: string
  policyImport: string
  /** `createOrderItemValidator`, `#validators/order_item` */
  createValidator: string
  updateValidator: string
  validatorImport: string
  /** Command line, for the header comment */
  command: string
}

/** List columns shown before the rest start hidden */
const VISIBLE_COLUMNS = 6

const quote = (value: string) => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`

/**
 * Words wrapped into ` * ` comment lines of up to 72 characters.
 */
function wrap(text: string) {
  const lines: string[] = []
  let line = ''
  for (const word of text.split(/\s+/)) {
    if (line && `${line} ${word}`.length > 72) {
      lines.push(line)
      line = word
    } else {
      line = line ? `${line} ${word}` : word
    }
  }
  if (line) lines.push(line)
  return lines.map((item) => ` * ${item}`)
}

function header(command: string, what: string, notes: string[] = []) {
  return [
    '/**',
    ...wrap(`Generated by \`${command}\`: ${what}`),
    ...notes.flatMap((note) => [' *', ...wrap(note)]),
    ' *',
    ...wrap('A starting point: edit it freely; Azu never regenerates it.'),
    ' */',
  ].join('\n')
}

function optionsMap(values: string[]) {
  return `{ ${values.map((value) => `${/^[A-Za-z_$][\w$]*$/.test(value) ? value : quote(value)}: ${quote(humanize(value))}`).join(', ')} }`
}

function fieldBuilder(field: FieldPlan) {
  switch (field.kind) {
    case 'select':
      return `field.select(${quote(field.name)}).options(${optionsMap(field.options ?? [])})`
    case 'belongsTo':
      return field.relation?.title
        ? `field.belongsTo(${quote(field.name)}).searchable(${quote(field.relation.title)})`
        : `field.belongsTo(${quote(field.name)})`
    default:
      return `field.${field.kind}(${quote(field.name)})`
  }
}

function columnBuilder(field: FieldPlan): string | null {
  switch (field.kind) {
    case 'text':
    case 'number':
    case 'decimal':
    case 'boolean':
    case 'date':
    case 'datetime':
      return `column.${field.kind}(${quote(field.name)}).sortable()`
    case 'select':
      return `column.badge(${quote(field.name)}).sortable()`
    case 'belongsTo':
      return field.relation?.title
        ? `column.belongsTo(${quote(field.name)}, ${quote(field.relation.title)})`
        : null
    default:
      // Long text stays off the list
      return null
  }
}

/**
 * `app/admin/resources/<model>_resource.ts`
 */
export function renderResource(
  plan: ModelPlan,
  names: Names,
  options: { validators: boolean }
): string {
  const columns: string[] = []
  const title = plan.fields.find((field) => field.name === plan.title)
  if (title) columns.push(columnBuilder(title)!)
  for (const field of plan.fields) {
    if (field === title) continue
    const built = columnBuilder(field)
    // The title and the next five columns show; the rest start hidden
    if (built) columns.push(columns.length < VISIBLE_COLUMNS ? built : `${built}.hiddenByDefault()`)
  }
  if (plan.createdAt)
    columns.push(`column.datetime(${quote(plan.createdAt)}).sortable().hiddenByDefault()`)

  const lines = [
    `import { column, defineResource, field } from '@mezielabs/azu'`,
    `import ${names.model} from '${names.modelImport}'`,
    `import ${names.policy} from '${names.policyImport}'`,
    options.validators
      ? `import { ${names.createValidator}, ${names.updateValidator} } from '${names.validatorImport}'`
      : null,
    '',
    header(names.command, `the admin resource for ${names.model}.`),
    `export default defineResource(${names.model}, {`,
    plan.title ? `  title: ${quote(plan.title)},` : null,
    plan.search.length > 0 ? `  search: [${plan.search.map(quote).join(', ')}],` : null,
    `  policy: ${names.policy},`,
    options.validators
      ? `  validators: { create: ${names.createValidator}, update: ${names.updateValidator} },`
      : null,
    '',
    '  columns: [',
    ...columns.map((built) => `    ${built},`),
    '  ],',
    '',
    '  fields: [',
    ...plan.fields.map((field) => `    ${fieldBuilder(field)},`),
    ...plan.manyToMany.map(
      (relation) =>
        `    field.manyToMany(${quote(relation.name)})${relation.title ? `.searchable(${quote(relation.title)})` : ''},`
    ),
    '  ],',
    '})',
    '',
  ]
  return lines.filter((line) => line !== null).join('\n')
}

/**
 * The VineJS rule for one field (spec §7).
 */
function rule(field: FieldPlan, plan: ModelPlan, update: boolean): string {
  const { column } = field
  let chain: string
  if (field.kind === 'belongsTo') {
    const base = column.type === 'integer' ? 'vine.number()' : 'vine.string()'
    chain = `${base}.exists({ table: ${quote(field.relation!.relatedTable)}, column: ${quote(field.relation!.relatedKeyColumn)} })`
  } else if (field.kind === 'select') {
    chain = `vine.enum([${(field.options ?? []).map(quote).join(', ')}] as const)`
  } else if (field.kind === 'boolean') {
    chain = 'vine.boolean()'
  } else if (field.kind === 'date' || field.kind === 'datetime') {
    chain = 'vine.date()'
  } else if (field.kind === 'number') {
    chain = column.type === 'integer' ? 'vine.number().withoutDecimals()' : 'vine.number()'
  } else if (field.kind === 'decimal') {
    const integer =
      column.precision !== null && column.scale !== null ? column.precision - column.scale : null
    const scale = column.scale
    const pattern =
      integer !== null && scale !== null
        ? `/^-?\\d{1,${Math.max(integer, 1)}}${scale > 0 ? `(\\.\\d{1,${scale}})?` : ''}$/`
        : '/^-?\\d+(\\.\\d+)?$/'
    // An exact string, like field.decimal(): validate the format, don't parse a float
    chain = `vine.string().trim().regex(${pattern})`
  } else {
    chain = 'vine.string().trim()'
    if (column.maxLength !== null && column.type === 'string')
      chain += `.maxLength(${column.maxLength})`
  }

  if (column.unique && field.kind !== 'belongsTo') {
    const where = `table: ${quote(plan.table)}, column: ${quote(column.name)}`
    chain += update
      ? [
          '.unique({',
          `    table: ${quote(plan.table)},`,
          `    column: ${quote(column.name)},`,
          '    filter: (query, _value, field) => {',
          `      query.whereNot(${quote(plan.primaryKeyColumn)}, field.meta.record.${plan.primaryKey})`,
          '    },',
          '  })',
        ].join('\n')
      : `.unique({ ${where} })`
  }

  if (column.nullable) chain += '.nullable().optional()'
  else if (column.hasDefault) chain += '.optional()'
  return chain
}

/**
 * `app/validators/<model>.ts`, or `<model>_admin.ts` when that's taken
 */
export function renderValidator(plan: ModelPlan, names: Names): string {
  const hasUnique = plan.fields.some((field) => field.column.unique && field.kind !== 'belongsTo')
  const block = (update: boolean) => [
    ...plan.fields.map((field) => `  ${field.input}: ${rule(field, plan, update)},`),
    // The related keys; left out, the attached records stay as they are
    ...plan.manyToMany.map(
      (relation) =>
        `  ${relation.input}: vine.array(${relation.integerKey ? 'vine.number()' : 'vine.string()'}.exists({ table: ${quote(relation.relatedTable)}, column: ${quote(relation.relatedKeyColumn)} })).optional(),`
    ),
  ]

  const lines = [
    `import vine from '@vinejs/vine'`,
    hasUnique ? `import type ${names.model} from '${names.modelImport}'` : null,
    '',
    header(
      names.command,
      `create and update validators for ${names.model}, derived from its database columns.`
    ),
    `export const ${names.createValidator} = vine.create({`,
    ...block(false),
    '})',
    '',
    hasUnique
      ? [
          '/**',
          ` * Azu passes \`{ record }\` as metadata: the ${string.noCase(names.model)} being edited, so its`,
          " * own values don't count as taken.",
          ' */',
          `export const ${names.updateValidator} = vine.withMetaData<{ record: ${names.model} }>().create({`,
        ].join('\n')
      : `export const ${names.updateValidator} = vine.create({`,
    ...block(true),
    '})',
    '',
  ]
  return lines.filter((line) => line !== null).join('\n')
}

/**
 * `app/policies/<model>_policy.ts`, with `--policy`
 */
export function renderPolicy(plan: ModelPlan, names: Names, options: { readonly: boolean }) {
  const records = string.plural(string.noCase(names.model))
  const canCreate = !options.readonly && plan.uncovered.length === 0
  const methods = [
    ['viewList', true],
    ['view', true],
    ['create', canCreate],
    ['update', !options.readonly],
  ] as const

  const notes = [
    `Everyone who passes the accessAdmin gate may use these. Narrow each method to the roles that should. There's no delete method, so deleting ${records} is denied until you add one.`,
  ]
  if (!options.readonly && !canCreate) {
    const columns = plan.uncovered.map((name) => `${plan.table}.${name}`).join(', ')
    notes.push(
      `There's no create method either: ${columns} ${plan.uncovered.length === 1 ? 'is' : 'are'} required but not an admin field, so ${records} can't be created here.`
    )
  }

  return [
    `import { BasePolicy } from '@adonisjs/bouncer'`,
    '',
    header(names.command, `the admin policy for ${names.model}.`, notes),
    `export default class ${names.policy} extends BasePolicy {`,
    methods
      .filter(([, included]) => included)
      .map(([method]) => `  ${method}() {\n    return true\n  }`)
      .join('\n\n'),
    '}',
    '',
  ].join('\n')
}
